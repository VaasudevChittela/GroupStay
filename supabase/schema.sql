-- ───────────── Who is who on a trip ─────────────
-- security definer so these can look across tables without tripping over the policies below.

create or replace function public.is_trip_advisor(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from trips t where t.id = p_trip_id and t.advisor_id = auth.uid())
      or exists (select 1 from trip_advisors a where a.trip_id = p_trip_id and lower(a.email) = lower(auth.email()));
$$;

create or replace function public.is_trip_member(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from guests g where g.trip_id = p_trip_id and g.user_id = auth.uid());
$$;

create or replace function public.is_trip_chaperone(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from guests g where g.trip_id = p_trip_id and g.user_id = auth.uid() and g.is_chaperone);
$$;

-- Hotel staff are matched by their (verified) login email against the trip's hotel email.
create or replace function public.is_trip_hotel(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from trips t where t.id = p_trip_id and lower(t.hotel_email) = lower(auth.email()));
$$;

create or replace function public.is_trip_participant(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_trip_advisor(p_trip_id) or public.is_trip_member(p_trip_id) or public.is_trip_hotel(p_trip_id);
$$;

create or replace function public.owns_guest(p_guest_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from guests g where g.id = p_guest_id and g.user_id = auth.uid());
$$;

-- ───────────── Functions the app calls ─────────────

-- Preview a trip by its code before joining (students can't read trips they aren't on yet).
create or replace function public.find_trip_by_code(p_code text) returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('id', id, 'name', name, 'hotel_name', hotel_name, 'hotel_address', hotel_address,
                           'school', school, 'check_in', check_in, 'check_out', check_out, 'locked_at', locked_at)
  from trips where upper(trip_code) = upper(trim(p_code)) limit 1;
$$;

-- Join the signed-in user to a trip. Reuses a guest row the advisor added with the same email.
create or replace function public.join_trip(
  p_trip_id bigint, p_full_name text, p_phone text, p_school text, p_gender text, p_is_chaperone boolean
) returns public.guests
language plpgsql security definer set search_path = public as $$
declare
  v_trip trips;
  v_guest guests;
begin
  if auth.uid() is null then raise exception 'Log in first.'; end if;
  select * into v_trip from trips where id = p_trip_id;
  if not found then raise exception 'Trip not found.'; end if;
  if v_trip.school is not null and lower(trim(v_trip.school)) <> lower(trim(p_school)) then
    raise exception 'This trip code is for %. Ask your advisor for your school''s code.', v_trip.school;
  end if;

  select * into v_guest from guests where trip_id = p_trip_id and user_id = auth.uid();
  if found then return v_guest; end if;

  update guests set user_id = auth.uid(),
                    phone = coalesce(nullif(phone, ''), p_phone),
                    gender = coalesce(gender, p_gender),
                    is_chaperone = is_chaperone or p_is_chaperone
   where id = (select id from guests where trip_id = p_trip_id and user_id is null
                 and lower(email) = lower(auth.email()) limit 1)
  returning * into v_guest;
  if found then return v_guest; end if;

  insert into guests (trip_id, user_id, legal_name, email, phone, school, gender, is_chaperone)
  values (p_trip_id, auth.uid(), p_full_name, auth.email(), p_phone, coalesce(v_trip.school, p_school), p_gender, p_is_chaperone)
  returning * into v_guest;
  return v_guest;
end;
$$;

-- Lock a trip whose room-pick deadline has passed and send the manifest. Any participant's app
-- calls this when it notices the deadline; it does nothing if already locked or not due.
create or replace function public.apply_lock_deadline(p_trip_id bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  v_trip trips;
begin
  if not public.is_trip_participant(p_trip_id) then return false; end if;
  update trips set locked_at = now(), manifest_sent_at = now()
   where id = p_trip_id and locked_at is null and lock_deadline is not null and lock_deadline <= now()
  returning * into v_trip;
  if not found then return false; end if;

  update room_requests set status = 'cancelled' where trip_id = p_trip_id and status = 'pending';
  insert into notifications (trip_id, audience, title, body, link) values
    (p_trip_id, 'staff', 'Manifest received', coalesce(v_trip.school, v_trip.name) || ' rooms locked automatically at the deadline.', 'manifest'),
    (p_trip_id, 'advisor', 'Rooms locked automatically',
     'The room-pick deadline passed, so ' || v_trip.name || ' is locked and the manifest went to the hotel.', 'assign');
  insert into notifications (trip_id, audience, guest_id, title, body, link)
    select p_trip_id, 'guest', id, 'Rooms are locked', 'The room-pick deadline passed. Check My Room for your final room.', 'rooms'
      from guests where trip_id = p_trip_id;
  return true;
end;
$$;

