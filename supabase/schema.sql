-- ───────────── Lock enforcement ─────────────
-- Once a trip is locked (or its deadline has passed), room assignments can't change.

create or replace function public.block_changes_when_locked() returns trigger
language plpgsql as $$
begin
  if exists (
    select 1 from public.trips
    where id = coalesce(new.trip_id, old.trip_id)
      and (locked_at is not null or (lock_deadline is not null and lock_deadline <= now()))
  ) then
    raise exception 'Room assignments are locked for this trip';
  end if;
  return coalesce(new, old);
end;
$$;

drop trigger if exists assignments_locked on public.assignments;
create trigger assignments_locked
  before insert or update or delete on public.assignments
  for each row execute function public.block_changes_when_locked();

-- ───────────── Row-level security ─────────────
-- Nobody sees a trip they aren't part of. Medical info and locations are tighter still.

do $$
declare t text;
begin
  foreach t in array array['trips', 'trip_advisors', 'rooms', 'guests', 'guest_details', 'assignments', 'messages',
                           'room_requests', 'notifications', 'locations', 'push_tokens'] loop
    execute format('alter table public.%I enable row level security', t);
    -- Remove the old allow-everything policy from earlier versions of this file.
    execute format('drop policy if exists "signed-in users" on public.%I', t);
  end loop;
end $$;

-- trips
drop policy if exists "trips: participants read" on public.trips;
create policy "trips: participants read" on public.trips for select to authenticated
  using (public.is_trip_participant(id));
drop policy if exists "trips: advisors create" on public.trips;
