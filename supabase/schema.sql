-- A parent is whoever a student listed as parent_email in My Info.
create or replace function public.is_parent_of(p_guest_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from guest_details d where d.guest_id = p_guest_id and lower(d.parent_email) = lower(auth.email()));
$$;

create or replace function public.is_trip_parent(p_trip_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from guest_details d where d.trip_id = p_trip_id and lower(d.parent_email) = lower(auth.email()));
$$;

-- Roommates' first names for a student's parent (parents can't read the full roster).
create or replace function public.roommate_names(p_guest_id bigint) returns text[]
language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(split_part(g.legal_name, ' ', 1) order by g.legal_name), '{}')
    from assignments mine
    join assignments a on a.room_id = mine.room_id and a.guest_id <> mine.guest_id
    join guests g on g.id = a.guest_id
   where mine.guest_id = p_guest_id
     and (public.is_parent_of(p_guest_id) or public.owns_guest(p_guest_id));
$$;

