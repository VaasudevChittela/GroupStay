drop policy if exists "guest_details: parents read own student" on public.guest_details;
create policy "guest_details: parents read own student" on public.guest_details for select to authenticated using (public.is_parent_of(guest_id));
drop policy if exists "messages: parents read announcements" on public.messages;
create policy "messages: parents read announcements" on public.messages for select to authenticated
  using (pinned and public.is_trip_parent(trip_id));
drop policy if exists "notifications: parents tell advisors" on public.notifications;
create policy "notifications: parents tell advisors" on public.notifications for insert to authenticated
  with check (audience = 'advisor' and public.is_trip_parent(trip_id));

-- permission_slips: parents sign for their own student; the student and advisors can see it.
drop policy if exists "permission_slips: read" on public.permission_slips;
create policy "permission_slips: read" on public.permission_slips for select to authenticated
  using (public.is_parent_of(guest_id) or public.owns_guest(guest_id) or public.is_trip_advisor(trip_id));
drop policy if exists "permission_slips: parent signs" on public.permission_slips;
create policy "permission_slips: parent signs" on public.permission_slips for insert to authenticated
  with check (public.is_parent_of(guest_id) and signed_email = auth.email());

-- schedule_items: advisors manage; everyone on the trip (and parents) reads.
drop policy if exists "schedule_items: read" on public.schedule_items;
create policy "schedule_items: read" on public.schedule_items for select to authenticated
  using (public.is_trip_participant(trip_id) or public.is_trip_parent(trip_id));
drop policy if exists "schedule_items: advisors manage" on public.schedule_items;
create policy "schedule_items: advisors manage" on public.schedule_items for all to authenticated
  using (public.is_trip_advisor(trip_id)) with check (public.is_trip_advisor(trip_id));

-- room_checks: chaperones and advisors.
drop policy if exists "room_checks: chaperones and advisors" on public.room_checks;
create policy "room_checks: chaperones and advisors" on public.room_checks for all to authenticated
  using (public.is_trip_chaperone(trip_id) or public.is_trip_advisor(trip_id))
  with check (public.is_trip_chaperone(trip_id) or public.is_trip_advisor(trip_id));

-- room_history: students and advisors add entries; advisors read the log.
drop policy if exists "room_history: write" on public.room_history;
create policy "room_history: write" on public.room_history for insert to authenticated
  with check (public.is_trip_member(trip_id) or public.is_trip_advisor(trip_id));
drop policy if exists "room_history: advisors read" on public.room_history;
create policy "room_history: advisors read" on public.room_history for select to authenticated
  using (public.is_trip_advisor(trip_id));
